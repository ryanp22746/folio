const {facetOptions}=require('./dist/search-ranking.js');
const facetRows=[{kind:'game',genres:['Action','Action'],platforms:['PS5'],release_date:'2024',inLibrary:true},{kind:'album',genres:['Vaporwave'],platforms:[],release_date:'2024'},{kind:'game',genres:['Vaporwave'],platforms:['PC'],release_date:'2023'}];
assert.deepEqual(facetOptions(facetRows,'genres',{platform:'PS5'}),[{value:'Action',count:1},{value:'Vaporwave',count:0}]);
assert.deepEqual(facetOptions(facetRows,'platforms',{genre:'Vaporwave'}),[{value:'PC',count:1},{value:'PS5',count:0}]);
assert.equal(facetOptions([...facetRows,{kind:'game',genres:['Vaporwave'],platforms:['PS5']}],'genres',{platform:'PS5'}).find(o=>o.value==='Vaporwave').count,1,'unusual real combinations must remain selectable');
assert.equal(facetOptions(facetRows,'genres',{kind:'game',year:'2024',owned:'new'}).every(o=>o.count===0),true);
