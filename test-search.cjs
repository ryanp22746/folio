const assert=require('node:assert/strict');
const {rank}=require('./dist/search-ranking.js');
const m=(title,count=0)=>({title,rating_count:count,source:{provider:'igdb'}});
assert.equal(rank([m('Portal Maze 2',5000),m('Portal 2: In Motion',200),m('Portal 2',100)],'Portal 2')[0].title,'Portal 2');
assert.equal(rank([m('Dune',20),m('Dune',500)],'Dune')[0].rating_count,500);
assert.equal(rank([m('Pokémon',20),m('Pokemon legends',500)],'pokemon')[0].title,'Pokémon');
console.log('Search relevance tests passed');
