const assert=require('node:assert/strict');
const facets=require('./dist/facets.js');
const manga={kind:'manga',genres:['Action','Shounen'],content_tags:['School life'],format:'Manga'};
const book={kind:'book',genres:['Romance'],content_tags:['Classic literature']};
const game={kind:'game',genres:['Sci-Fi'],platforms:['PS5']};
assert.deepEqual(facets.values(book,'demographic'),[]);
assert.deepEqual(facets.values(manga,'demographic'),['Shounen']);
assert(facets.matches(manga,{genres:{action:1},demographic:{shounen:1}}));
assert(!facets.matches(book,{demographic:{shounen:1}}));
assert(!facets.matches(manga,{tags:{'school life':-1}}));
assert(facets.matches(book,{mode:'any',genres:{romance:1,action:1}}));
assert(!facets.matches(book,{mode:'all',genres:{romance:1,action:1}}));
assert(facets.matches(game,{genres:{'science fiction':1},platforms:{'playstation 5':1}}));
assert.deepEqual(facets.options([{kind:'game',genres:['Sci-Fi']},{kind:'movie',genres:['Science fiction']}],'genres').map(o=>o.count),[2]);
const {sources}=require('./dist/album-tracks.js');
const apple={kind:'album',id:'apple:album:1',source:{provider:'apple',id:'1'}};
assert.equal(sources({...apple,source_records:[apple,{kind:'track',source:{provider:'spotify',id:'2'}}]}).length,1);
const alternateSpotify={kind:'album',id:'spotify:album:other',source:{provider:'spotify',id:'other'},facts:{Edition:'Explicit'}};
const selectedClean={...apple,facts:{Edition:'Clean'},version_options:[alternateSpotify]};
assert.equal(sources(selectedClean)[0].source.provider,'apple','Selected clean album must not default to another explicit listing');
const {same,group}=require('./dist/identity.js');
const album=(provider,facts={})=>({id:provider+':album:1',kind:'album',title:'Album',creators:['Artist'],release_date:'2020-01-01',facts,source:{provider},external_ids:{}});
assert(same(album('spotify'),album('apple')));
assert.equal(group([album('spotify'),album('apple'),album('musicbrainz')]).length,1);
assert(!same(album('spotify',{Tracks:'10'}),album('apple',{Tracks:'12'})));
assert(!same(album('spotify',{Edition:'Explicit'}),album('apple',{Edition:'Clean'})));
assert(!same({...album('spotify'),kind:'track',facts:{Duration:'3:00'}},{...album('apple'),kind:'track',facts:{Duration:'4:00'}}));
const {editions}=require('./dist/identity.js');
assert.equal(editions([album('spotify'),{...album('spotify'),id:'spotify:album:2'}]).length,1);
const reissues=editions([album('spotify'),{...album('apple'),release_date:'2022-01-01'}]);
assert.equal(reissues.length,1);assert.equal(reissues[0].version_options.length,1);
assert.equal(editions([album('spotify'),{...album('apple'),creators:['Unrelated artist']}]).length,2);
assert.equal(editions([{...album('spotify'),kind:'track'},{...album('apple'),kind:'track',release_date:'2009-01-01'}]).length,1);
assert.equal(editions([{...album('spotify'),kind:'track',external_ids:{isrc:'USAAA2000001'}},{...album('apple'),kind:'track',external_ids:{isrc:'USAAA2000001'}}]).length,1);
assert(same({id:'jikan:anime:1',kind:'anime',format:'Movie',source:{provider:'jikan'},external_ids:{myanimelist:'1'}},{id:'mal:anime:1',kind:'anime',format:'movie',source:{provider:'mal'},external_ids:{myanimelist:'1'}}));
const {creatorQuery,nameMatch}=require('./dist/creator-search.js');
assert.equal(creatorQuery('studio trigger'),'trigger');assert(nameMatch('TRIGGER','Studio Trigger'));
const {linkedEntity}=require('./dist/creators.js');
assert(linkedEntity({entity_links:['https://www.example.com/creator/']},{entity_links:['https://example.com/creator']}));
assert(!linkedEntity({entity_links:['https://x.com/']},{entity_links:['https://x.com/']}));
assert(linkedEntity({entity_links:['https://music.apple.com/us/artist/name/123']},{entity_links:['https://music.apple.com/us/artist/123']}));
assert.deepEqual(facets.options([manga,book],'genres',{demographic:{shounen:1}}).find(o=>o.value==='romance').count,0);
assert.equal(facets.options([],'genres',{genres:{action:1}})[0].value,'action','selected tags remain removable when a new query has no hits');
const {eligible}=require('./dist/associations.js');
assert(eligible('Ryuuko Matoi','anime',''));assert(!eligible('Studio Trigger','',''));assert(!eligible('Jane Austen','book',''));
const search=require('./dist/search-ranking.js');
assert.equal(search.rank([{title:'Obscure trigger',source:{provider:'tmdb'}},{title:'Kill la Kill',rating_count:50000,source:{provider:'mal'},discovery_context:{query:'Studio Trigger'}}],'Studio Trigger')[0].title,'Kill la Kill');
assert.deepEqual(search.variants('Panty and Stocking'),['Panty and Stocking','Panty Stocking']);
console.log('Adaptive facets, album editions, verified creator links, character scope, and associated search ranking passed');

const collection=require('./dist/collections.js');
const show={id:'tmdb:tv:7',kind:'tv',source:{provider:'tmdb',id:'7'},external_ids:{tmdb:'7'}};
const season={...show,id:'tmdb:tv:7-season-1',source:{provider:'tmdb',id:'7-season-1'},external_ids:{tmdb:'7-season-1'}};
assert(!require('./dist/identity.js').same(show,season),'whole show and season are separate library entries');
assert.equal(collection.sources({source_records:[show,show]}).length,1);
assert.equal(collection.sources({kind:'book',source:{provider:'openlibrary',id:'OL1W'}}).length,0);
assert.equal(collection.related({related_media:[{provider:'mal',kind:'anime',id:'1'},{provider:'mal',kind:'anime',id:'1'}]}).length,1);
