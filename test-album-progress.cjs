const assert=require('node:assert/strict');
const {key,update,progress}=require('./dist/album-progress.js');
const a={id:'spotify:track:a',facts:{Disc:'1','Track number':'1'}},b={...a,facts:{Disc:'2','Track number':'1'}};
assert.notEqual(key(a),key(b));
let state=update(null,'spotify:album',[a,b],[key(a)],true,true);
assert.deepEqual(progress(state,'spotify:album'),{completed:1,total:null});
const prior=structuredClone(state);
state=update(state,'spotify:album',[a,b],[key(a),key(b)],true,false);
assert.deepEqual(progress(state,'spotify:album'),{completed:2,total:2});
assert.deepEqual(progress(prior,'spotify:album'),{completed:1,total:null});
state=update(state,'spotify:album',[a,b],[key(a)],false,false);
assert.deepEqual(progress(state,'spotify:album'),{completed:1,total:2});
assert.deepEqual(progress(state,'apple:edition'),{completed:0,total:null});
state=update(state,'apple:edition',[a],[key(a)],true,false);
assert.deepEqual(progress(state,'spotify:album'),{completed:1,total:2});
assert.deepEqual(progress(state,'apple:edition'),{completed:1,total:1});
console.log('Album completion: track slots, pagination, edition isolation, undo and immutable saves passed');
const partial=update(state,'spotify:album',[a],[key(a)],true,true);
assert.deepEqual(progress(partial,'spotify:album'),{completed:2,total:2});
